-- PostgreSQL 18 Production Schema for Ruang Baca
-- Source of truth: specs/database-contracts.md & database/prisma/schema.prisma

CREATE TABLE IF NOT EXISTS accounts (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  role TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  account_id TEXT NOT NULL UNIQUE REFERENCES accounts(id) ON DELETE CASCADE ON UPDATE CASCADE,
  nama_lengkap TEXT NOT NULL,
  no_hp TEXT NOT NULL,
  alamat TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS admins (
  id TEXT PRIMARY KEY,
  account_id TEXT NOT NULL UNIQUE REFERENCES accounts(id) ON DELETE CASCADE ON UPDATE CASCADE,
  nama_lengkap TEXT NOT NULL,
  no_hp TEXT NOT NULL,
  alamat TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categories (
  id SERIAL PRIMARY KEY,
  nama_kategori TEXT NOT NULL,
  jenis_buku TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS books (
  id SERIAL PRIMARY KEY,
  categories_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  judul TEXT NOT NULL,
  penulis TEXT NOT NULL,
  penerbit TEXT NOT NULL,
  sinopsis TEXT NOT NULL,
  tanggal_rilis TIMESTAMPTZ NOT NULL,
  stok INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS temp_peminjaman (
  id SERIAL PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE ON UPDATE CASCADE,
  tanggal_peminjaman TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS peminjaman (
  id SERIAL PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  admin_id TEXT NOT NULL REFERENCES admins(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  tanggal_peminjaman TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  tanggal_batas_peminjaman TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS temp_pengembalian (
  id SERIAL PRIMARY KEY,
  peminjaman_id INTEGER NOT NULL REFERENCES peminjaman(id) ON DELETE CASCADE ON UPDATE CASCADE,
  tanggal_dikembalikan TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS pengembalian (
  id SERIAL PRIMARY KEY,
  peminjaman_id INTEGER NOT NULL REFERENCES peminjaman(id) ON DELETE CASCADE ON UPDATE CASCADE,
  tanggal_dikembalikan TIMESTAMPTZ NOT NULL,
  status_buku TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS refresh_token (
  id SERIAL PRIMARY KEY,
  account_id TEXT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE ON UPDATE CASCADE,
  token TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expired_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS laporan (
  id SERIAL PRIMARY KEY,
  admin_id TEXT NOT NULL REFERENCES admins(id) ON DELETE CASCADE ON UPDATE CASCADE,
  keterangan TEXT NOT NULL,
  total_denda DOUBLE PRECISION NOT NULL,
  total_peminjam INTEGER NOT NULL DEFAULT 0,
  tanggal_awal_peminjaman TIMESTAMPTZ NOT NULL,
  tanggal_akhir_peminjaman TIMESTAMPTZ NOT NULL,
  tanggal_awal_pengembalian TIMESTAMPTZ NOT NULL,
  tanggal_akhir_pengembalian TIMESTAMPTZ NOT NULL,
  tanggal_pembuatan_laporan TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS daftar_denda (
  id SERIAL PRIMARY KEY,
  pengembalian_id INTEGER NOT NULL REFERENCES pengembalian(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  denda DOUBLE PRECISION NOT NULL,
  keterangan TEXT NOT NULL
);
